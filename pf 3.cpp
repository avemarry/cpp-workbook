// C++ ის მმართველი ოპერატორები: if, else და ლოგიკური ოპერატორები
// სრული კონსპექტი (აბრევიატურები, დანიშნულება, დატვირთვა და გამოყენება)


// 1. მმართველი ოპერატორი if (თუ)
// • რას აკეთებს: ამოწმებს მოცემულ პირობას. თუ პირობა ჭეშმარიტია (true / 1), 
//   ასრულებს მის ფიგურულ ფრჩხილებში მოქცეულ კოდს. თუ არა - გვერდს უვლის.
// • რატომ ვიყენებთ: პროგრამას ვასწავლით გადაწყვეტილებების მიღებას 
//   სხვადასხვა სიტუაციაში (მაგ: პაროლის შემოწმება, ქულის დაწერა).
// • სინტაქსი და მაგალითი:
//   if (x > 0) {
//       cout << "Positive";
//   }

// 2. ოპერატორი else (სხვა შემთხვევაში)
// • რას აკეთებს: მუშაობს მხოლოდ მაშინ, როდესაც შესაბამისი if-ის პირობა 
//   აღმოჩნდება მცდარი (false / 0). ის არის "დანარჩენი ყველა შემთხვევა".
// • რატომ ვიყენებთ: როდესაც გვინდა განვსაზღვროთ რა ქნას პროგრამამ 
//   მაშინ, როცა ძირითადი პირობა არ შესრულდა (მაგ: უარყოფითი ან ნული).
// • სინტაქსი და მაგალითი:
//   if (x > 0) {
//       cout << "Positive";
//   } else {
//       cout << "Not positive";
//   }

// 3. მრავალჯერადი არჩევანი: else if (სხვა ანუ თუ...)
// • რას აკეთებს: ამოწმებს ახალ პირობას, თუ წინა if ან else if მცდარი იყო.
// • რატომ ვიყენებთ: როცა გვაქვს 2-ზე მეტი შესაძლო ვარიანტი (მაგ: მეტია, 
//   ნაკლებია თუ ტოლია).
// • მაგალითი:
//   if (x > 0) { cout << "Greater"; }
//   else if (x < 0) { cout << "Less"; }
//   else { cout << "Equal"; }

// 4. შედარების ოპერატორები (რას ვწერთ ფრჩხილებში)
// • ==  -> უდრის (ყურადღება: ერთიანი `=` მინიჭებაა, ორიანი `==` შედარება).
// • !=  -> არ უდრის.
// • >   -> მეტია.
// • <   -> ნაკლებია.
// • >=  -> მეტია ან ტოლი (გამოიყენება სორტირებისას და ტოლობების აცილებისთვის).
// • <=  -> ნაკლებია ან ტოლი.

// 5. ლოგიკური ოპერატორები (რამდენიმე პირობის ერთად შეერთება)
// • &&  (AND / და) -> ორივე პირობა ერთდროულად უნდა იყოს ჭეშმარიტი.
//   - რატომ ვიყენებთ: მაგალითად, ორნიშნიანი რიცხვის ასაღებად: (num >= 10 && num <= 99).
// • ||  (OR / ან)  -> მინიმუმ ერთი პირობა მაინც უნდა იყოს ჭეშმარიტი.
//   - რატომ ვიყენებთ: როცა გვინდა რამდენიმე ალტერნატივიდან ერთ-ერთი მაინც დაკმაყოფილდეს.
// • !   (NOT / არა) -> ატრიალებს მნიშვნელობას ჭეშმარიტიდან მცდარზე და პირიქით.

// 6. ნაშთიანი გაყოფის ოპერატორი (%) - ხშირად გამოყენებული if-ებთან
// • რას აკეთებს: აბრუნებს გაყოფისას მიღებულ ნაშთს.
// • რატომ ვიყენებთ: ლუწი/კენტის დასადგენად (num % 2 == 0) ან იმის 
//   გასაგებად, იყოფა თუ არა რიცხვი უნაშთოდ (a % b == 0).
// • მაგალითი: 7 % 2 აბრუნებს 1-ს (კენტია); 8 % 2 აბრუნებს 0-ს (ლუწია).

// 7. ჩადგმული if-ები (Nested if)
// • რას აკეთებს: if-ის შიგნით იწერება კიდევ ერთი სხვა if.
// • რატომ ვიყენებთ: როდესაც მთავარი პირობის შესრულების შემდეგ 
//   საჭიროა კიდევ უფრო დეტალური შემოწმებების გავლა 
//   (მაგალითად, სამი რიცხვის დალაგებისას სორტირების დროს).

/* ამოცანა N1 შემოდის ერთი მთელი დადებითი რიცხვი. დაადგინეთ არის თუ არა ერთნიშნა რიცხვი. 
შესაბამისად ამობეჭდეთ "YES" ან "NO" */

#include <iostream>
using namespace std;

int main()
{
    int x;       // ქმნის ცარიელ მთელრიცხვოვან ცვლადს სახელად x
    cin >> x;    // მომხმარებლის მიერ შეყვანილ რიცხვს ინახავს x-ში
    
    if (x > -10 && x < 10)  // ამოწმებს პირობას: არის თუ არა x ნაკლები 10-ზე
    {
        cout << "YES"; // თუ პირობა ჭეშმარიტია, ეკრანზე გამოაქვს "YES"
    }
    else         // სხვა შემთხვევაში (თუ x მეტია ან ტოლია 10-ის)
    {
        cout << "NO" << endl; // ეკრანზე გამოაქვს "NO" და გადადის ახალ ხაზზე
    }
    
    return 0;    // ასრულებს პროგრამას
}

/* ამოცანა N2 შემოდის ერთი მთელი დადებითი რიცხვი. დაადგინეთ არის თუ არა ერთნიშნა რიცხვი */
